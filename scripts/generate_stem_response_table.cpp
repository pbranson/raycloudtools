// Generates raylib/raystemresponsetable.h: the free path response ray::freePathResponse for non-overlapping stems
// with no minimum gap, on the interpolation grid of ray::StemResponseTable, for both return range conventions.
// The values are deterministic (fixed seeds), so this only needs rerunning when the simulation or the grid changes.
//
// Build against raylib (in a raycloudtools build directory <build>, for the source directory <src>), e.g.:
//   g++ -O2 -std=c++17 -I<src> -I<src>/raylib -I<build>/raylib -I<build> -I/usr/include/eigen3
//     <src>/scripts/generate_stem_response_table.cpp -L<build>/raylib -lraylib -lpthread
//     -o generate_stem_response_table
// and run (about 10 minutes with 2 threads):
//   LD_LIBRARY_PATH=<build>/raylib ./generate_stem_response_table [num_threads=2] > <src>/raylib/raystemresponsetable.h
#include "raylib/raystemmodel.h"

#include <atomic>
#include <chrono>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <iostream>
#include <thread>
#include <vector>

int main(int argc, char *argv[])
{
  const int num_threads = argc > 1 ? std::max(1, std::atoi(argv[1])) : 2;
  // the grid of exclusion disc solid fractions and width ratios. Finer at high solid fractions, where the response
  // is strongly convex
  const std::vector<double> fractions = { 0.0, 0.01, 0.02, 0.04, 0.07, 0.1, 0.13, 0.16, 0.2, 0.25, 0.3, 0.35, 0.4 };
  const double ratio_step = 0.25;
  const int num_ratios = 17;  // width ratios 1 to 5
  const size_t num_fractions = fractions.size();
  struct Node
  {
    int convention;
    size_t f;
    int r;
  };
  std::vector<Node> nodes;
  // surface convention first, as it is the cheaper
  for (int convention = 0; convention < 2; convention++)
  {
    for (size_t f = 0; f < num_fractions; f++)
    {
      for (int r = 0; r < num_ratios; r++)
      {
        nodes.push_back({ convention, f, r });
      }
    }
  }
  std::vector<double> values(nodes.size(), 1.0);
  std::atomic<size_t> next(0);
  const auto begin = std::chrono::steady_clock::now();
  auto worker = [&]() {
    for (size_t i = next++; i < nodes.size(); i = next++)
    {
      const Node &node = nodes[i];
      const auto t0 = std::chrono::steady_clock::now();
      values[i] = ray::freePathResponse(fractions[node.f], 1.0 + ratio_step * node.r, 0.0, node.convention == 1);
      const double seconds = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
      std::fprintf(stderr, "%s fraction %g ratio %g: %.6f (%.2f s)\n", node.convention == 1 ? "outline" : "surface",
                   fractions[node.f], 1.0 + ratio_step * node.r, values[i], seconds);
    }
  };
  std::vector<std::thread> threads;
  for (int t = 0; t < num_threads; t++)
  {
    threads.emplace_back(worker);
  }
  for (auto &thread : threads)
  {
    thread.join();
  }
  std::fprintf(stderr, "total %.1f s\n",
               std::chrono::duration<double>(std::chrono::steady_clock::now() - begin).count());

  std::printf("// Copyright (c) 2026\n");
  std::printf("// Commonwealth Scientific and Industrial Research Organisation (CSIRO)\n");
  std::printf("// ABN 41 687 119 230\n");
  std::printf("//\n");
  std::printf("// Generated by scripts/generate_stem_response_table.cpp. Do not edit.\n");
  std::printf("#ifndef RAYLIB_RAYSTEMRESPONSETABLE_H\n#define RAYLIB_RAYSTEMRESPONSETABLE_H\n\n#include <limits>\n\n");
  std::printf("// clang-format off\nnamespace ray\n{\nnamespace stem_response\n{\n");
  std::printf("/// The grid of ray::StemResponseTable: solid fractions (of the exclusion discs) and width ratios\n");
  std::printf("constexpr int kNumFractions = %d;\n", static_cast<int>(num_fractions));
  std::printf("constexpr double kFractions[kNumFractions] = { ");
  for (size_t f = 0; f < num_fractions; f++)
  {
    std::printf("%s%.15g", f > 0 ? ", " : "", fractions[f]);
  }
  std::printf(" };\n");
  std::printf("constexpr int kNumRatios = %d;\n", num_ratios);
  std::printf("constexpr double kRatioStep = %.15g;  // width ratios 1, 1 + step, ...\n", ratio_step);
  std::printf("/// A grid value with effectively no free space, so the response is unbounded\n");
  std::printf("constexpr double kSaturated = std::numeric_limits<double>::infinity();\n");
  std::printf("/// ray::freePathResponse(fraction, ratio, 0, range_to_outline) for range_to_outline false (index 0)\n");
  std::printf("/// and true (index 1). A NaN value would be computed when needed\n");
  std::printf("constexpr double kGapZero[2][kNumFractions][kNumRatios] = {\n");
  for (int convention = 0; convention < 2; convention++)
  {
    std::printf("  {  // %s\n", convention == 1 ? "range to the widened outline" : "range to the physical surface");
    for (size_t f = 0; f < num_fractions; f++)
    {
      std::printf("    { ");
      for (int r = 0; r < num_ratios; r++)
      {
        const double value =
          values[(static_cast<size_t>(convention) * num_fractions + f) * num_ratios + static_cast<size_t>(r)];
        if (std::isinf(value))
        {
          std::printf("%skSaturated", r > 0 ? ", " : "");
        }
        else
        {
          std::printf("%s%.17g", r > 0 ? ", " : "", value);
        }
      }
      std::printf(" },\n");
    }
    std::printf("  },\n");
  }
  std::printf("};\n}  // namespace stem_response\n}  // namespace ray\n// clang-format on\n#endif  // "
              "RAYLIB_RAYSTEMRESPONSETABLE_H\n");
  return 0;
}
